export type ChatRole = "user" | "assistant";

/**
 * The visual contract.
 *
 * The model picks a `kind` and a set of IDs. It NEVER passes arbitrary chart
 * data, markup, or JSX. Every visual is rendered by a React component that
 * reads from the validated content layer (`content/*.yaml`) or from the
 * retrieval index, so a visual can never show a number that is not already
 * verified.
 *
 * An unknown or invalid spec falls back to `UnknownCard`, which states
 * honestly that there is no verified visual for the answer.
 */
export type VisualSpec =
  | { kind: "profile" }
  | { kind: "education" }
  | { kind: "skills" }
  | { kind: "project"; projectId: string }
  | { kind: "architecture"; projectId: string }
  | { kind: "flow"; projectId: string }
  | {
      kind: "data-model";
      projectId: string;
      /**
       * The captured tables and their relations.
       *
       * SERVER OWNED. The model is only allowed to name the project; the
       * entities are read from `content/datamodel/<projectId>.json`, which is
       * generated from the indexed schema files. A model-supplied `entities`
       * array is stripped before the spec reaches the wire, so a prompt
       * injection cannot put invented tables into the diagram.
       */
      entities?: DataModelEntity[];
    }
  | {
      kind: "code";
      projectId: string;
      path: string;
      startLine: number;
      endLine: number;
      /**
       * The exact source lines the citation points at.
       *
       * SERVER OWNED. The server re-reads the range out of the source index
       * and attaches the real text; a model-supplied `code` string is
       * stripped before the spec reaches the wire, so a prompt injection
       * cannot put arbitrary text into the code viewer. A spec without an
       * attached source renders an honest "no source attached" state rather
       * than a fabricated file.
       */
      code?: string;
      /** A Shiki language id, e.g. `python`. Inferred from `path` when absent. */
      language?: string;
    }
  | {
      kind: "comparison";
      projectIds: string[];
      dimension?: string;
      /** Resolved comparison rows. Derived from the project index when absent. */
      rows?: ComparisonRow[];
    }
  | {
      kind: "metrics";
      projectId?: string;
      /**
       * The verified numbers, with the method, source and date that make
       * them checkable.
       *
       * SERVER OWNED. The rows come from `content/metrics.yaml`; the model
       * is only allowed to name the project.
       */
      rows?: MetricRow[];
    }
  | { kind: "claims"; claimIds: string[] }
  | { kind: "contact" };

/**
 * One table in a captured data model.
 *
 * The entity is only ever drawn when it came from the verified content
 * layer, so the shape mirrors what a reviewer can check.
 */
export type DataModelEntity = {
  name: string;
  fields: {
    name: string;
    type: string;
    required?: boolean;
    /** The related entity this field points at, when it is a foreign key. */
    relation?: string;
  }[];
  relations?: {
    from: string;
    to: string;
    label: string;
    kind?: "1-1" | "1-n" | "n-n";
  }[];
};

/**
 * A captured data model, as stored in `content/datamodel/<projectId>.json`.
 *
 * The file is GENERATED by `scripts/index/datamodel.ts` from the indexed
 * schema files, so every entity can be traced back to a real `CREATE TABLE`
 * or Mongoose schema. The `source` string is the list of files the
 * extraction read, which is what makes the diagram checkable.
 */
export type DataModelDocument = {
  /** The project id the document belongs to. */
  project: string;
  /** The script that generated the file. */
  generatedBy: string;
  /** The files the entities were extracted from. */
  source: string;
  entities: DataModelEntity[];
};

/** One project as shown next to its peers in a comparison. */
export type ComparisonRow = {
  id: string;
  name: string;
  tagline?: string;
  status?: string;
  stack?: string[];
  metrics?: { label: string; value: string; note?: string }[];
  caveats?: string[];
  summary?: string;
};

/** One verified number, with the method and source that make it checkable. */
export type MetricRow = {
  label: string;
  value: string;
  unit?: string;
  method: string;
  source: string;
  verifiedAt: string;
};


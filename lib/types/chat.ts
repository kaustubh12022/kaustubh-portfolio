/**
 * The file extensions the code viewer knows how to highlight.
 *
 * WHY THIS LIVES IN THE SHARED CONTRACT
 * -------------------------------------
 * The server attaches the language of a `code` visual so the wire payload is
 * self-describing, and the client infers it as a fallback for a spec that
 * arrived without one. Both sides therefore need the SAME table, and the
 * shared chat-contract module is the one place both can import from without
 * the server pulling a React component (and Shiki) into its own bundle.
 */
const PATH_LANGUAGES: Record<string, string> = {
  ".py": "python",
  ".js": "javascript",
  ".mjs": "javascript",
  ".cjs": "javascript",
  ".jsx": "jsx",
  ".ts": "typescript",
  ".tsx": "tsx",
  ".java": "java",
  ".sql": "sql",
  ".html": "html",
  ".htm": "html",
  ".css": "css",
  ".scss": "scss",
  ".dart": "dart",
  ".yaml": "yaml",
  ".yml": "yaml",
  ".json": "json",
  ".md": "markdown",
  ".sh": "bash",
  ".go": "go",
  ".rs": "rust",
  ".rb": "ruby",
  ".php": "php",
};

/**
 * Best-effort language id for a file path.
 *
 * @param path a repo-relative POSIX path
 * @returns a Shiki language id, or `"text"` when the extension is unknown
 */
export function inferLanguage(path: string): string {
  const match = path.match(/\.([a-z0-9]+)$/i);
  if (!match) return "text";
  const extension = `.${match[1].toLowerCase()}`;
  return PATH_LANGUAGES[extension] ?? match[1].toLowerCase();
}

export type ChatMessage = {
  id: string;
  role: ChatRole;
  text: string;
  visual?: VisualSpec;
  evidence?: string[];
  followUps?: string[];
  /** Set while the answer is still streaming in. */
  pending?: boolean;
  /** The confidence the server assigned to this answer. */
  confidence?: "high" | "medium" | "low";
  /** Honest caveats attached to the answer. */
  caveats?: string[];
};

/**
 * A citation into the source index.
 *
 * `path` and the line range are resolved SERVER-SIDE against the pinned
 * commit before the answer is emitted, so a model cannot invent a line
 * number: an unresolvable reference is dropped and the answer's confidence is
 * downgraded.
 */
export type EvidenceRef = {
  projectId: string;
  path: string;
  startLine: number;
  endLine: number;
  symbol?: string;
  /**
   * The exact source lines the answer relied on.
   *
   * The validator re-reads the index and compares this against the file at
   * [startLine, endLine]. A citation whose quote does not match is dropped,
   * so a model cannot invent a line number and keep the citation.
   */
  quote?: string;
  /** A short human-readable label, e.g. "src/ai_engine.py:59". */
  label: string;
  /** True when the reference was verified against the pinned commit. */
  verified: boolean;
};

export type DemoAnswer = {
  text: string;
  visual?: VisualSpec;
  evidence?: string[];
  followUps?: string[];
};
